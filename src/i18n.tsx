export function formatBytes(value: number, language: Language) {
  const megabytes = value >= 1024 * 1024
  const amount = megabytes ? value / 1024 / 1024 : value / 1024
  return `${new Intl.NumberFormat(language, { minimumFractionDigits: megabytes ? 2 : 1, maximumFractionDigits: megabytes ? 2 : 1 }).format(amount)} ${megabytes ? (language === 'ru' ? 'МБ' : 'MB') : (language === 'ru' ? 'КБ' : 'KB')}`
}
