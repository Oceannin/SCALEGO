const dictionaries = { ru, en }
const STORAGE_KEY = 'scalego-language'

function initialLanguage(): Language {
  const saved = localStorage.getItem(STORAGE_KEY)
  if (saved === 'ru' || saved === 'en') return saved
  return navigator.language.toLowerCase().startsWith('ru-') || navigator.language.toLowerCase() === 'ru' ? 'ru' : 'en'
}

function interpolate(value: string, params: Params = {}) {
  return value.replace(/\{(\w+)\}/g, (_match, key) => String(params[key] ?? ''))
}

export type Translate = (key: TranslationKey, params?: Params) => string

interface I18nValue { language: Language; setLanguage: (language: Language) => void; t: Translate }
const I18nContext = createContext<I18nValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(initialLanguage)
  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, language)
    document.documentElement.lang = language
    document.title = dictionaries[language]['document.title']
  }, [language])
  const value = useMemo<I18nValue>(() => ({
    language,
    setLanguage,
    t: (key, params) => interpolate(dictionaries[language][key], params),
  }), [language])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider')
  return value
}

export function translateMessage(t: Translate, namespace: 'stage' | 'warning' | 'error' | 'engine', message?: UserMessage | string | null) {
  if (!message) return ''
  const code = typeof message === 'string' ? message : message.code
  const params = typeof message === 'string' ? undefined : message.params
  const key = `${namespace}.${code}` as TranslationKey
  return Object.hasOwn(ru, key) ? t(key, params) : namespace === 'error' ? t('error.UNEXPECTED_ERROR') : ''
}

export function localizeError(t: Translate, error: unknown) {
  if (error && typeof error === 'object' && 'code' in error) {
    return translateMessage(t, 'error', { code: String(error.code), params: 'params' in error && typeof error.params === 'object' ? error.params as Params : undefined })
  }
  return t('error.UNEXPECTED_ERROR')
}

